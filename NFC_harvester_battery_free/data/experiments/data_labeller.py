def balance_dataframe(df, labelby):
    """
    Balances a dataframe by randomly deleting samples. Will delete samples until all labels have the same amount of occurences as the least occuring label in the dataframe.

    Parameters
    ----------
    df : DataFrame
        The dataframe to be balanced.
    labelby : str
        Classification labels to balance on.
    
    Returns
    -------
    df : DataFrame
        The balanced dataframe.
    """
    sample_size = df[labelby].value_counts().min()

    new_set = []
    for label in df[labelby].value_counts().index:
        new_set.append(resample(df[df[labelby]==label], replace=True, n_samples=sample_size, random_state=42))

    df = pd.concat(new_set)

    print(f"Dataframe for {labelby} after balancing: ")
    print(df[labelby].value_counts().to_string(header=False))

    return df