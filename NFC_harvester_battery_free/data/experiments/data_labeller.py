def get_time_series(df, label):
    """
    Creates a list of time series chunks from a given dataframe for a given label. A chunk is a consecutive part of the dataset where labels are the same.

    Parameters
    ----------
    df : DataFrame
        Dataframe from which chunks should be obtained.
    label : str
        Label on which should be filtered. List of chunks will only contain chunks for this label.

    Returns
    -------
    chunks : list of DataFrame
        List of chunks with a given label from a given Dataframe.
    """
    df = df[df['label']==label]

    # Find consecutive indices
    consecutive_indices = df.index.to_series().diff().fillna(1) != 1
    consecutive_index_groups = consecutive_indices.cumsum()

    # Get chunks of DataFrame
    chunks = [group_df for _, group_df in df.groupby(consecutive_index_groups)]

    return chunks

def get_time_series_df(df, labelby):
    """
    Convert a given dataframe into a time-series based dataframe. Instead of data per sample, will contain data per event. Will filter based on labelby.

    Parameters
    ----------
    df : DataFrame
        The dataframe to be converted. Contains data per sample.
    labelby : Act or str
        The classification to filter on.
    
    Returns
    -------
    df : DataFrame
        Time-series based dataframe, filtered on labelby classification.
    """
    time_series_features_list = []

    # Get all the labels in the dataframe.
    labels = np.unique(df['label'])

    whitelist = []

    # Obtain the whitelist to determine which labels should be included.
    if labelby not in timeseries_whitelists:
        whitelist = [
            "Wear with mouth closed",
            "Wear with mouth open",
            "Speaking",
            "Get ready to drink",
            "Drinking",
            "Rest with mouth closed"
            ]
    else:
        whitelist = timeseries_whitelists[labelby]

    # Convert labels into time-series based labels. Also create time-series based features. Append these labels and features to a temporary list.
    for label in labels:
        if label not in whitelist:
            continue
        ts = get_time_series(df,label)
        for t in ts:
            resultant_var = t['resultant'].var()
            pd_var = t['m_pd'].var()
            temp_diff_min = t['m_temp'].diff().min()
            speaking_state = 'Speaking' if label=='Speaking' else 'Not_speaking'
            drinking_state = 'Drinking' if label=='Drinking' else 'Not_drinking'
            grinding_state = 'Grinding' if label=='Grinding' else 'Not grinding'
            grinding_state_extended = 'Grinding' if label=='Grinding' else 'Speaking' if label == 'Speaking' else 'Not grinding'
            awake_asleep_ts = 'Awake' if label=='Awake' else 'Asleep'
            time_series_features_list.append([label,resultant_var,pd_var,temp_diff_min,speaking_state,drinking_state, grinding_state, grinding_state_extended, awake_asleep_ts])

    # Create the new time-series based temporary list.
    df_new = pd.DataFrame(time_series_features_list, columns=['label', 'resultant_var','pd_var','temp_diff_min','speaking_state','drinking_state', 'grinding_state', 'grinding_state_extended', 'awake_asleep_ts'])
    return df_new

