def normalise_pd(df):
    """
    Normalises all photodiode readings in a given dataframe (in place). Normalises based on the maximum and minimum value in the given dataframe.

    Parameters
    ----------
    df : DataFrame
        The dataframe from which the photodiode column should be normalized.

    Returns
    -------
    df : DataFrame
        The dataframe with normalized photodiode values. 
    """
    if 'm_pd' in df.columns.values.tolist():
        mini = df['m_pd'].min()
        maxi = df['m_pd'].max()
        diff = maxi - mini
        normalised = [((x-mini)/diff) for x in df['m_pd']]
        df['m_pd'] = normalised
    return df

def fix_drinking(df):
    """
    Manually fix the issue where all drinking readings are labeled as "unknown", due to it only lasting 5 seconds. Fixes the labels in place.

    Parameters
    ----------
    df : DataFrame
        The dataframe from which the drinking labels should be modified.

    Returns
    -------
    df : DataFrame
        The dataframe with drinking labels. 
    """
    to_drink = False
    rest_with_mouth_closed = False
    fixed = []

    for l in df['label']:
        if 'Get ready to drink' in l:
            to_drink = True
        if 'Rest with mouth closed' in l:
            rest_with_mouth_closed = True

        if (to_drink and not rest_with_mouth_closed) and (l == 'unkown' or l == 'unknown'):
            fixed.append('Drinking')
        else:
            fixed.append(l)
    fixed = pd.Series(fixed)
    df['label'] = fixed

    return df

def convert_accelerometer(df, device):
    """
    Converts the accelerometer readings in a dataframe from a 16-bit signed integer to a float in g. 

    Parameters
    ----------
    df : DataFrame
        The dataframe in which the accelerometer readings should possibly be converted
    device : Devices or str
        The device from which the data was collected. 

    Returns
    -------
    df : DataFrame
        The dataframe with possibly accelerometer readings converted to floats in g
    """
    device_settings = accel_labels[device]
    if device_settings["convert_values"]:
        df[device_settings["x"]] = df[device_settings["x"]]/16384
        df[device_settings["y"]] = df[device_settings["y"]]/16384
        df[device_settings["z"]] = df[device_settings["z"]]/16384

    return df

def append_open_close_transition(df, window_size):
    """
    Appends transition between opened and closed labels in a given window to a given dataframe.

    Parameters
    ----------
    df : DataFrame
        The dataframe to which open/close transition should be appended.

    Returns
    -------
    df : DataFrame
        The dataframe with mouth open/close transition appended. 
    """
    side_size = int((window_size - 1) / 2) # assuming uneven window_size
    labels = df["label"]
    transition_labels = []
    for i in range(labels.size):
        left_idx = max(0, int(i - side_size))
        right_idx = min(labels.size, int(i + side_size) + 1)

        window = labels.iloc[left_idx:right_idx]
        if window.str.contains("Mouth open").any() and window.str.contains("Mouth closed").any():
            if window.iloc[0] == "Mouth open":
                transition_labels.append("Opening")
            else:
                transition_labels.append("Closing")
        elif window.str.contains("Mouth open").any() or window.str.contains("Mouth closed").any():
            transition_labels.append("Stable")
        else:
            transition_labels.append("NA")
    df = df.assign(oc_transition=transition_labels)
    return df

