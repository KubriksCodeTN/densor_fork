def append_abs_rolling_avg_column(window, column, df, new_column=None):
    """
    Appends the rolling average of a given column to a given dataframe. If new_column is set to None, the rolling average will be applied in place.

    Parameters
    ----------
    window : int
        The window size used for the average.
    column : str
        The column label for the input column.
    df : DataFrame
        The dataframe to which the rolling average should be appended.
    new_column : str, optional
        Label of the column to which the rolling average should be written. If None, overwrites the input column.
    
    Returns
    -------
    df : DataFrame
        The dataframe with appended rolling average.
    """
    if new_column == None:
        new_column = column

    df[new_column] = df[column].abs().rolling(window, min_periods=1, center=True).mean()
    return df

