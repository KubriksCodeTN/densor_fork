def get_all_data(pid=None, files_path=None, device=Devices.densor):
    """
    Loads and concatenates data from all files in a given folder into one dataframe.

    Parameters
    ----------
    pid : int, optional
        Indentification number of the test subject to filter on. If set to any int, will only consider data from that test subject. If set to None, will consider data from all test subjects.
    files_path : str, optional
        Path to folder to search in. Include "*.csv" to the end of the folder path to only search for csv files. When set to None, will default to "labeled_data/*.csv".
    device : Devices or str, default=Devices.densor
        Device on which all data is collected.
    """
    df_list = []
    files = get_list_of_files(files_path)
    for file in files:
        pid_file = int(file.split('-')[3][1:])

        if pid != None:
            if pid_file != pid and pid_file != 0:
                continue
        df_list.append(get_data_from_csv(file, pid_file, device))
    return pd.concat(df_list,ignore_index=True)

